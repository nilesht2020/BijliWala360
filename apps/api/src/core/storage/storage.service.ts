export interface PresignedUpload {
  url: string;
  method: 'PUT';
  headers: Record<string, string>;
  expiresAt: Date;
}

export interface ObjectHead {
  sizeBytes: number;
  contentType?: string;
}

/** Keys are generated by the server only: "<area>/<24-hex id>" (e.g. quarantine/6731...). */
const KEY_PATTERN = /^(quarantine|clean|exports|public)\/[a-f0-9]{24}$/;

export function assertStorageKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new DomainError('VALIDATION_FAILED', 'Invalid storage key.');
}

interface StorageDriver {
  presignUpload(
    key: string,
    contentType: string,
    sizeBytes: number,
    ttlSeconds: number,
  ): Promise<PresignedUpload>;
  presignDownload(key: string, ttlSeconds: number, options?: DownloadOptions): Promise<string>;
  head(key: string): Promise<ObjectHead | null>;
  getBuffer(key: string, maxBytes: number): Promise<Buffer>;
  putBuffer(key: string, body: Buffer, contentType: string): Promise<void>;
  move(fromKey: string, toKey: string): Promise<void>;
  delete(key: string): Promise<void>;
}

export interface DownloadOptions {
  /** File name suggested to the browser. */
  fileName?: string;
  /**
   * `true` lets the browser display the file in the tab (PDF viewer / image) instead of
   * saving it. Only use for content whose type was verified on upload (PDF, JPEG, PNG, WebP).
   */
  inline?: boolean;
}

function contentDisposition(name: string, inline = false): string {
  return `${inline ? 'inline' : 'attachment'}; filename="${name.replace(/[^\w.\- ]/g, '_')}"`;
}

/* --------------------------------------------------------------------------- S3 */

class S3Driver implements StorageDriver {
  private readonly s3: S3Client;
  private readonly bucket: string;

  constructor(env: AppConfig['env']) {
    this.bucket = env.S3_BUCKET;
    this.s3 = new S3Client({
      region: env.S3_REGION,
      ...(env.S3_ENDPOINT ? { endpoint: env.S3_ENDPOINT } : {}),
      forcePathStyle: env.S3_FORCE_PATH_STYLE,
      ...(env.S3_ACCESS_KEY_ID && env.S3_SECRET_ACCESS_KEY
        ? { credentials: { accessKeyId: env.S3_ACCESS_KEY_ID, secretAccessKey: env.S3_SECRET_ACCESS_KEY } }
        : {}),
    });
  }

  async presignUpload(
    key: string,
    contentType: string,
    sizeBytes: number,
    ttlSeconds: number,
  ): Promise<PresignedUpload> {
    const command = new PutObjectCommand({
      Bucket: this.bucket,
      Key: key,
      ContentType: contentType,
      ContentLength: sizeBytes,
      ServerSideEncryption: 'AES256',
    });
    return {
      url: await getSignedUrl(this.s3, command, { expiresIn: ttlSeconds }),
      method: 'PUT',
      headers: { 'Content-Type': contentType, 'x-amz-server-side-encryption': 'AES256' },
      expiresAt: new Date(Date.now() + ttlSeconds * 1000),
    };
  }

  presignDownload(key: string, ttlSeconds: number, options: DownloadOptions = {}): Promise<string> {
    const { fileName, inline } = options;
    const command = new GetObjectCommand({
      Bucket: this.bucket,
      Key: key,
      ...(fileName
        ? { ResponseContentDisposition: contentDisposition(fileName, inline) }
        : inline
          ? { ResponseContentDisposition: 'inline' }
          : {}),
    });
    return getSignedUrl(this.s3, command, { expiresIn: ttlSeconds });
  }

  async head(key: string): Promise<ObjectHead | null> {
    try {
      const res = await this.s3.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key }));
      return { sizeBytes: res.ContentLength ?? 0, contentType: res.ContentType };
    } catch (err) {
      if ((err as { name?: string }).name === 'NotFound') return null;
      throw err;
    }
  }

  async getBuffer(key: string, maxBytes: number): Promise<Buffer> {
    const res = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    const chunks: Buffer[] = [];
    let total = 0;
    for await (const chunk of res.Body as Readable) {
      total += (chunk as Buffer).length;
      if (total > maxBytes)
        throw new DomainError('UPLOAD_TOO_LARGE', 'The uploaded file is larger than allowed.');
      chunks.push(chunk as Buffer);
    }
    return Buffer.concat(chunks);
  }

  async putBuffer(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.s3.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Body: body,
        ContentType: contentType,
        ServerSideEncryption: 'AES256',
      }),
    );
  }

  async move(fromKey: string, toKey: string): Promise<void> {
    await this.s3.send(
      new CopyObjectCommand({
        Bucket: this.bucket,
        CopySource: `${this.bucket}/${encodeURIComponent(fromKey)}`,
        Key: toKey,
        ServerSideEncryption: 'AES256',
      }),
    );
    await this.delete(fromKey);
  }

  async delete(key: string): Promise<void> {
    await this.s3.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

/* --------------------------------------------------------------------------- local disk (dev only) */

export class LocalDiskDriver implements StorageDriver {
  readonly root: string;

  constructor(
    dir: string,
    private readonly secret: string,
  ) {
    this.root = resolve(dir);
  }

  pathFor(key: string): string {
    assertStorageKey(key);
    const full = resolve(this.root, key);
    if (!full.startsWith(this.root + sep)) throw new DomainError('VALIDATION_FAILED', 'Invalid storage key.');
    return full;
  }

  sign(op: 'put' | 'get', key: string, exp: number, extra = ''): string {
    return createHmac('sha256', this.secret).update(`${op}|${key}|${exp}|${extra}`).digest('hex');
  }

  verify(op: 'put' | 'get', key: string, exp: number, sig: string, extra = ''): boolean {
    if (!Number.isFinite(exp) || exp < Date.now() / 1000) return false;
    const expected = Buffer.from(this.sign(op, key, exp, extra));
    const given = Buffer.from(sig ?? '');
    return expected.length === given.length && timingSafeEqual(expected, given);
  }

  async presignUpload(
    key: string,
    contentType: string,
    sizeBytes: number,
    ttlSeconds: number,
  ): Promise<PresignedUpload> {
    this.pathFor(key);
    const exp = Math.floor(Date.now() / 1000) + ttlSeconds;
    const extra = `${contentType}|${sizeBytes}`;
    const qs = new URLSearchParams({
      exp: String(exp),
      sig: this.sign('put', key, exp, extra),
      ct: contentType,
      len: String(sizeBytes),
    });
    return {
      // Relative URL: the web app reaches it through its /api proxy, exactly like the API itself.
      url: `/api/v1/dev-storage/${encodeURIComponent(key)}?${qs.toString()}`,
      method: 'PUT',
      headers: { 'Content-Type': contentType },
      expiresAt: new Date(exp * 1000),
    };
  }

  async presignDownload(key: string, ttlSeconds: number, options: DownloadOptions = {}): Promise<string> {
    this.pathFor(key);
    const exp = Math.floor(Date.now() / 1000) + ttlSeconds;
    const name = options.fileName ?? '';
    const inline = options.inline ? '1' : '';
    const qs = new URLSearchParams({
      exp: String(exp),
      sig: this.sign('get', key, exp, `${name}|${inline}`),
      ...(name ? { name } : {}),
      ...(inline ? { inline } : {}),
    });
    return `/api/v1/dev-storage/${encodeURIComponent(key)}?${qs.toString()}`;
  }

  async head(key: string): Promise<ObjectHead | null> {
    try {
      const [st, meta] = await Promise.all([
        stat(this.pathFor(key)),
        readFile(`${this.pathFor(key)}.meta.json`, 'utf8'),
      ]);
      return { sizeBytes: st.size, contentType: (JSON.parse(meta) as { contentType?: string }).contentType };
    } catch {
      return null;
    }
  }

  async getBuffer(key: string, maxBytes: number): Promise<Buffer> {
    const buf = await readFile(this.pathFor(key));
    if (buf.length > maxBytes)
      throw new DomainError('UPLOAD_TOO_LARGE', 'The uploaded file is larger than allowed.');
    return buf;
  }

  async putBuffer(key: string, body: Buffer, contentType: string): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body);
    await writeFile(`${path}.meta.json`, JSON.stringify({ contentType }));
  }

  async move(fromKey: string, toKey: string): Promise<void> {
    const to = this.pathFor(toKey);
    await mkdir(dirname(to), { recursive: true });
    await rename(this.pathFor(fromKey), to);
    await rename(`${this.pathFor(fromKey)}.meta.json`, `${to}.meta.json`);
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
    await rm(`${this.pathFor(key)}.meta.json`, { force: true });
  }
}

/**
 * Private object storage (ARCHITECTURE §6.7). Objects are never public; uploads land in
 * `quarantine/` and move to `clean/` only after the file checks pass. Driver: S3-compatible
 * (production) or local disk with HMAC-signed URLs (development without MinIO).
 */
@Injectable()
export class StorageService implements StorageDriver {
  private readonly driver: StorageDriver;
  readonly local: LocalDiskDriver | null;

  constructor(config: AppConfig) {
    if (config.env.STORAGE_DRIVER === 'local') {
      this.local = new LocalDiskDriver(config.env.LOCAL_STORAGE_DIR, config.env.HASH_PEPPER);
      this.driver = this.local;
    } else {
      this.local = null;
      this.driver = new S3Driver(config.env);
    }
  }

  presignUpload(
    key: string,
    contentType: string,
    sizeBytes: number,
    ttlSeconds: number,
  ): Promise<PresignedUpload> {
    return this.driver.presignUpload(key, contentType, sizeBytes, ttlSeconds);
  }
  presignDownload(key: string, ttlSeconds: number, options?: DownloadOptions): Promise<string> {
    return this.driver.presignDownload(key, ttlSeconds, options);
  }
  head(key: string): Promise<ObjectHead | null> {
    return this.driver.head(key);
  }
  getBuffer(key: string, maxBytes: number): Promise<Buffer> {
    return this.driver.getBuffer(key, maxBytes);
  }
  putBuffer(key: string, body: Buffer, contentType: string): Promise<void> {
    return this.driver.putBuffer(key, body, contentType);
  }
  move(fromKey: string, toKey: string): Promise<void> {
    return this.driver.move(fromKey, toKey);
  }
  delete(key: string): Promise<void> {
    return this.driver.delete(key);
  }
}

const MAX_DEV_UPLOAD_BYTES = 25 * 1024 * 1024;

/** Serves signed PUT/GET URLs for the local-disk driver. Returns 404 unless STORAGE_DRIVER=local. */
@ApiExcludeController()
@Controller('dev-storage')
@Public()
@SkipRateLimit()
export class DevStorageController {
  constructor(private readonly storage: StorageService) {}

  private driver(): LocalDiskDriver {
    if (!this.storage.local) throw new DomainError('NOT_FOUND', 'Not found.');
    return this.storage.local;
  }

  @Put(':key')
  @HttpCode(200)
  @RawResponse()
  async upload(
    @Param('key') key: string,
    @Query() q: Record<string, string>,
    @Req() req: Request,
  ): Promise<{ stored: true }> {
    const driver = this.driver();
    const contentType = req.headers['content-type'] ?? '';
    const extra = `${q.ct ?? ''}|${q.len ?? ''}`;
    if (!driver.verify('put', key, Number(q.exp), q.sig ?? '', extra) || contentType !== q.ct) {
      throw new DomainError('FORBIDDEN', 'Upload URL is invalid or has expired.');
    }
    const chunks: Buffer[] = [];
    let total = 0;
    for await (const chunk of req) {
      total += (chunk as Buffer).length;
      if (total > MAX_DEV_UPLOAD_BYTES || total > Number(q.len)) {
        throw new DomainError('UPLOAD_TOO_LARGE', 'The file is larger than declared.');
      }
      chunks.push(chunk as Buffer);
    }
    if (total !== Number(q.len))
      throw new DomainError('VALIDATION_FAILED', 'File size does not match the declared size.');
    await driver.putBuffer(key, Buffer.concat(chunks), contentType);
    return { stored: true };
  }

  @Get(':key')
  @RawResponse()
  async download(
    @Param('key') key: string,
    @Query() q: Record<string, string>,
    @Res() res: Response,
  ): Promise<void> {
    const driver = this.driver();
    const inline = q.inline === '1';
    if (!driver.verify('get', key, Number(q.exp), q.sig ?? '', `${q.name ?? ''}|${inline ? '1' : ''}`)) {
      throw new DomainError('FORBIDDEN', 'Download URL is invalid or has expired.');
    }
    const head = await driver.head(key);
    if (!head) throw new DomainError('NOT_FOUND', 'File not found.');
    res.setHeader('Content-Type', head.contentType ?? 'application/octet-stream');
    res.setHeader('X-Content-Type-Options', 'nosniff');
    if (q.name) res.setHeader('Content-Disposition', contentDisposition(q.name, inline));
    else if (inline) res.setHeader('Content-Disposition', 'inline');
    // Helmet's CSP (object-src 'none') stops the browser's PDF viewer rendering inside the app's
    // viewer frame. Like S3 in production, serve verified inline files without it.
    if (inline) res.removeHeader('Content-Security-Policy');
    res.send(await driver.getBuffer(key, MAX_DEV_UPLOAD_BYTES));
  }
}

@Global()
@Module({ controllers: [DevStorageController], providers: [StorageService], exports: [StorageService] })
export class StorageModule {}
